/**
 * Search cities by name / state / country (case-insensitive).
 * Ranking: name prefix → state/country prefix → substring anywhere. Empty query → first `limit` cities.
 */
export function searchCities(query: string, limit = 20): City[] {
  const q = query.trim().toLowerCase();
  if (!q) return CITIES.slice(0, limit);
  const namePrefix: City[] = [];
  const otherPrefix: City[] = [];
  const substring: City[] = [];
  for (const c of CITIES) {
    const name = c.name.toLowerCase();
    const state = c.state.toLowerCase();
    const country = c.country.toLowerCase();
    if (name.startsWith(q)) namePrefix.push(c);
    else if (state.startsWith(q) || country.startsWith(q)) otherPrefix.push(c);
    else if (name.includes(q) || state.includes(q) || country.includes(q)) substring.push(c);
  }
  return [...namePrefix, ...otherPrefix, ...substring].slice(0, limit);
}
